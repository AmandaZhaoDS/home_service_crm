type TranslationMap = typeof T.en;
type TranslationKey = keyof TranslationMap;

interface LangContextValue {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: TranslationKey) => string;
  dir: 'ltr' | 'rtl';
}

const LangContext = createContext<LangContextValue>({
  lang: 'en', setLang: () => {}, t: (k) => k, dir: 'ltr',
});

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>('en');

  useEffect(() => {
    const saved = localStorage.getItem('fpLang') as Lang | null;
    if (saved && T[saved]) setLangState(saved);
  }, []);

  const setLang = (l: Lang) => {
    setLangState(l);
    localStorage.setItem('fpLang', l);
    const info = LANGUAGES.find(x => x.code === l);
    document.documentElement.dir = info?.dir ?? 'ltr';
    document.documentElement.lang = l;
  };

  useEffect(() => {
    const info = LANGUAGES.find(x => x.code === lang);
    document.documentElement.dir = info?.dir ?? 'ltr';
    document.documentElement.lang = lang;
  }, [lang]);

  const t = (key: TranslationKey): string => {
    const map = (T[lang] ?? T.en) as Record<string, string>;
    return map[key] ?? (T.en as Record<string, string>)[key] ?? key;
  };

  const dir = (LANGUAGES.find(x => x.code === lang)?.dir ?? 'ltr') as 'ltr' | 'rtl';

  return (
    <LangContext.Provider value={{ lang, setLang, t, dir }}>
      {children}
    </LangContext.Provider>
  );
}

export function useLanguage() { return useContext(LangContext); }
export function useT() { return useContext(LangContext).t; }
